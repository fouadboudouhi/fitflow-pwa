// Builds the exercise catalogue from the public dataset and the curated selection:
//   node tools/import-exercises.mjs /path/to/exercises.json
// Writes assets/data/exercises.js, assets/data/steps.en.js and assets/data/steps.de.js, and refreshes the
// `ex.<id>` names in src/locales/de.js and en.js. The output is deterministic, so re-running changes nothing.
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const datasetPath = process.argv[2];
if (!datasetPath) {
  console.error('usage: node tools/import-exercises.mjs <path to the dataset exercises.json>');
  process.exit(1);
}
const dataset = new Map(JSON.parse(readFileSync(datasetPath, 'utf8')).map((x) => [x.id, x]));
const read = (name) => JSON.parse(readFileSync(join(root, 'tools', name), 'utf8'));
const selection = read('exercise-selection.json');
const steps = { en: read('steps.en.json'), de: read('steps.de.json') };

const records = selection.map((s) => {
  const rec = dataset.get(s.id);
  if (!rec) throw new Error(`${s.id} is not in the dataset`);
  const secondary = [...new Set((rec.secondary_muscles || []).filter((m) => m && m !== rec.target))];
  return {
    id: s.id,
    name: rec.name,
    category: rec.category,
    equipment: rec.equipment,
    target: rec.target,
    ...(secondary.length ? { secondary } : {}),
    file: basename(rec.gif_url),
    ...(s.trackType ? { trackType: s.trackType } : {}),
  };
});

const header = '// Generated by tools/import-exercises.mjs. Do not edit by hand.';
writeFileSync(
  join(root, 'assets/data/exercises.js'),
  `${header}\n// Catalogue from the YaKohen exercises dataset and tools/exercise-selection.json; media is hot-linked (see THIRD_PARTY_ASSETS.md).\nexport const EXERCISES = [\n${records.map((r) => `  ${JSON.stringify(r)},`).join('\n')}\n];\n`
);
for (const lang of ['en', 'de']) {
  writeFileSync(
    join(root, `assets/data/steps.${lang}.js`),
    `${header}\n// Step-by-step instructions (${lang}), loaded on demand by the exercise sheet.\nexport default {\n${selection.map((s) => `  ${JSON.stringify(s.id)}: ${JSON.stringify(steps[lang][s.id] || [])},`).join('\n')}\n};\n`
  );
}

const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
for (const [file, key] of [
  ['src/locales/de.js', 'nameDe'],
  ['src/locales/en.js', 'nameEn'],
]) {
  const path = join(root, file);
  const src = readFileSync(path, 'utf8');
  const block = `const exercises = {\n${selection.map((s) => `  'ex.${s.id}': ${quote(s[key])},`).join('\n')}\n};`;
  const next = src.replace(/const exercises = \{[\s\S]*?\n\};/, block);
  if (next === src) throw new Error(`exercise block not found in ${file}`);
  writeFileSync(path, next);
}
console.log(`${records.length} exercises, ${Object.keys(steps.en).length} instruction sets written`);
